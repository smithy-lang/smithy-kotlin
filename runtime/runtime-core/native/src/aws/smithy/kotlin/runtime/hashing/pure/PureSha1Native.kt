/**
 * Native SHA-1 block function: all 80 rounds written out, with the schedule kept in 16 local words w0..w15 (a ring)
 * and the state variables renamed each round instead of moved. Native otherwise stores every schedule word to memory;
 * this measured 1.61-1.78x on native but 0.72-0.79x on the JVM.
 */
internal actual fun sha1ProcessBlocks(state: IntArray, schedule: IntArray, input: ByteArray, offset: Int, count: Int) {
