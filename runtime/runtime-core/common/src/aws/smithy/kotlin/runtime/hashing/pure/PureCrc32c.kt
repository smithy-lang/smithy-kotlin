package aws.smithy.kotlin.runtime.hashing.pure

import aws.smithy.kotlin.runtime.hashing.Crc32Base

/**
 * Pure-Kotlin CRC32C: runtime-core's [aws.smithy.kotlin.runtime.hashing.Crc32c] algorithm with its lookup table stored
 * as an [IntArray] instead of a boxed `List<Long>`, and read into a local once per update.
 */
internal class PureCrc32c : Crc32Base() {
    private val md = CRC32CImpl()

    override fun update(input: ByteArray, offset: Int, length: Int) {
        checkRange(input.size, offset, length)
        md.update(input, offset, length)
    }

    override fun digestValue(): UInt = md.getValue().toUInt().also { reset() }

    override fun reset(): Unit = md.reset()
}

